// Calculadora - 28/08/2026
function calculadora(a, b, operacao) {
    if(operacao == '+'){
        console.log(a + b)
    } else if(operacao == '-'){
        console.log(a - b)
    } else if(operacao == '*'){
        console.log(a * b)
    } else if(operacao == '/'){
        console.log(a / b)
    }
}

calculadora(10, 8, '-')
